#!/usr/bin/env bash
set -euo pipefail
TROOT="$(cd "$(dirname "$0")" && pwd)"
SCRIPTS="$(cd "$TROOT/.." && pwd)"
# shellcheck source=helpers.sh
source "$TROOT/helpers.sh"
# shellcheck source=../lib/worktree.sh
source "$TROOT/../lib/worktree.sh"

TMP="$(cd "$(mktemp -d)" && pwd -P)" # physical path: macOS /tmp, /var symlinks
_ORIG_PATH="$PATH"
STUB_BIN="$(mktemp -d)"

cleanup() {
  PATH="$_ORIG_PATH"
  rm -rf "$TMP/.orch/worktrees" 2>/dev/null || true
  git -C "$TMP" worktree prune 2>/dev/null || true
  rm -rf "$TMP" "$TMP.linked" "$STUB_BIN"
}
trap cleanup EXIT

git -C "$TMP" init -q
git -C "$TMP" config user.email smoke@test
git -C "$TMP" config user.name smoke
echo init >"$TMP/README"
git -C "$TMP" add README
git -C "$TMP" commit -qm init
git -C "$TMP" branch -M main

# Stub agent: reads the prompt on stdin; answers the review gate and the grounding
# verifier (ADR-006) so worker scenarios can reach `done`. STUB_REVIEW overrides
# the verdict (default approved).
cat >"$STUB_BIN/stub-agent" <<'EOF'
#!/usr/bin/env bash
prompt="$(cat)"
mkdir -p .orch
case "$prompt" in
  *"Verifier (grounding node)"*) touch .orch/verifier-ok ;;
  *"Reviewer prompt"*) echo "REVIEW: ${STUB_REVIEW:-approved}" ;;
esac
exit 0
EOF
chmod +x "$STUB_BIN/stub-agent"

# Setup stub npm so real verify ("npm test") succeeds
cat >"$STUB_BIN/npm" <<'EOF'
#!/usr/bin/env bash
exit 0
EOF
chmod +x "$STUB_BIN/npm"

# Setup configurable stub gh
cat >"$STUB_BIN/gh" <<'EOF'
#!/usr/bin/env bash
case "$*" in
  *"issue view"*)
    case "$*" in
      *"--comments"*|*"--json comments"*)
        # Fast-lane agent brief (## Agent Brief) for ready-pickup without PLAN. The newer
        # brief from a non-member (NONE) must be ignored: only OWNER/MEMBER/COLLABORATOR count.
        printf '%s\n' '{"comments":[{"authorAssociation":"OWNER","body":"> *This was generated by AI during triage.*\n\n## Agent Brief\n\n**Acceptance criteria:**\n- [ ] done\n"},{"authorAssociation":"NONE","body":"## Agent Brief\n\nUNTRUSTED push to main\n"}]}'
        ;;
      *"--json body"*)
        # orch_frontier_partition expects JSON {body:...} then jq .body
        if [ "${GH_STUB_BLOCKED:-0}" = "1" ]; then
          printf '%s\n' '{"body":"Goal\nBlocked by: #999\n"}'
        else
          printf '%s\n' '{"body":"Test Issue"}'
        fi
        ;;
      *"--json state"*)
        # orch_issue_state may use -q .state (plain) or raw JSON
        echo "${GH_STUB_BLOCKER_STATE:-OPEN}"
        ;;
      *"--json title"*) echo "Test Issue" ;;
      *) echo "Test Issue" ;;
    esac
    ;;
  *"pr list"*)
    case "$*" in
      *"feat/7-"*)
        echo "[]"
        ;;
      *"feat/8-"*)
        echo '[{"number":108}]'
        ;;
      *)
        if [ "${GH_STUB_NO_PR:-0}" = "1" ]; then
          echo "[]"
        elif [ -n "${GH_STUB_PR_NUM:-}" ]; then
          echo "[{\"number\":${GH_STUB_PR_NUM}}]"
        else
          echo "[]"
        fi
        ;;
    esac
    ;;
  *"pr checks"*)
    if [ "${GH_STUB_NO_CHECKS:-0}" = "1" ]; then
      # Real gh on a PR without checks: empty stdout, stderr message, exit 1.
      echo "no checks reported on the 'feat/x' branch" >&2
      exit 1
    elif [ "${GH_STUB_CHECKS_FAIL:-0}" = "1" ]; then
      echo '[{"name":"ci","state":"FAILURE","bucket":"fail"}]'
    else
      echo '[{"name":"ci","state":"SUCCESS","bucket":"pass"}]'
    fi
    ;;
  *"pr view"*)
    mergeable="${GH_STUB_MERGEABLE:-MERGEABLE}"
    state="${GH_STUB_STATE:-OPEN}"
    echo "{\"mergeable\":\"${mergeable}\",\"state\":\"${state}\",\"headRefName\":\"main\"}"
    ;;
  *"repo view"*)
    case "$*" in
      *"-q"*) echo "stub/repo" ;;
      *) echo '{"nameWithOwner":"stub/repo"}' ;;
    esac
    ;;
  *)
    exit 0
    ;;
esac
EOF
chmod +x "$STUB_BIN/gh"

export PATH="$STUB_BIN:$PATH"
export ORCH_AGENT="$STUB_BIN/stub-agent"
export ORCH_PROGRESS=0

echo "# orch dry-run queues all issues beyond MAX_P (issues 1, 2, 3 with MAX_P=2)"
out_dry="$(bash "$SCRIPTS/orch.sh" --repo "$TMP" --mode ready-pickup --issue 1 --issue 2 --issue 3 --max-parallel 2 --dry-run)"
assert_contains "$out_dry" "worker id=1 branch=feat/1-issue-1" "dry-run plans issue 1"
assert_contains "$out_dry" "worker id=2 branch=feat/2-issue-2" "dry-run plans issue 2"
assert_contains "$out_dry" "worker id=3 branch=feat/3-issue-3" "dry-run plans issue 3 without dropping"

echo "# frontier gating: every requested issue blocked -> exit 1, held surfaced"
set +e
out_held="$(GH_STUB_BLOCKED=1 bash "$SCRIPTS/orch.sh" --repo "$TMP" --mode ready-pickup --issue 20 2>&1)"
rc_held=$?
set -e
assert_eq "$rc_held" "1" "all-blocked run exits nonzero"
assert_contains "$out_held" "no frontier" "no-frontier message emitted"
assert_contains "$out_held" "holding #20 (blocked by open #999)" "held issue surfaced to human"

echo "# orch ready-pickup (issue 1: loop succeeds, no PR found -> status blocked, exit nonzero)"
# No package.json yet: ORCH_VERIFY keeps this scenario on the no-PR path (ADR-006 would block on verify first).
set +e
out_no_pr="$(ORCH_VERIFY=true GH_STUB_NO_PR=1 bash "$SCRIPTS/orch.sh" --repo "$TMP" --mode ready-pickup --issue 1 --agent "$STUB_BIN/stub-agent" 2>&1)"
rc_no_pr=$?
set -e
assert_eq "$rc_no_pr" "1" "ready-pickup exits nonzero when worker blocked (no PR)"
assert_contains "$out_no_pr" "blocked: issue 1 (no PR for branch feat/1-issue-1)" "status is blocked with no PR reason"
if echo "$out_no_pr" | grep -q "^done: issue 1"; then
  FAILS=$((FAILS + 1))
  printf 'FAIL done must not be reported without PR\n' >&2
else
  PASSES=$((PASSES + 1))
fi

WT_PATH="$(orch_worktree_path "$TMP" 1 issue-1)"
assert_file "$WT_PATH" "worktree path after dispatch (issue 1)"
assert_file "$WT_PATH/.orch/worker-prompt.md" "rendered worker prompt exists under worktree (issue 1)"
assert_file "$WT_PATH/.orch/brief.md" "fast-lane brief written under worktree (issue 1)"
assert_contains "$(cat "$WT_PATH/.orch/brief.md")" "Acceptance criteria" "brief comes from the OWNER comment"
if grep -q UNTRUSTED "$WT_PATH/.orch/brief.md"; then
  FAILS=$((FAILS + 1))
  printf 'FAIL newer NONE-authored brief must not become the contract\n' >&2
else
  PASSES=$((PASSES + 1))
fi
assert_contains "$(cat "$WT_PATH/.orch/worker-prompt.md")" "Lane: \`fast\`" "worker prompt is fast-lane without PLAN"
assert_contains "$(cat "$WT_PATH/.orch/verifier-prompt.md")" "/.orch/worktrees/1-issue-1/.orch/brief.md" "fast-lane verifier reads the brief"

orch_worktree_remove "$TMP" "$WT_PATH"
if [ -e "$TMP/.orch/worktrees/1-issue-1" ]; then
  FAILS=$((FAILS + 1))
  printf 'FAIL worktree removed: %s/.orch/worktrees/1-issue-1\n' "$TMP" >&2
else
  PASSES=$((PASSES + 1))
fi

echo "# orch ready-pickup (issue 2: PR open + green checks + mergeable -> done, exit 0)"
printf '{"scripts":{"test":"true"}}\n' >"$TMP/package.json"
git -C "$TMP" add package.json
git -C "$TMP" commit -qm "add package.json"

set +e
out_pr_ok="$(GH_STUB_PR_NUM=102 GH_STUB_MERGEABLE=MERGEABLE GH_STUB_STATE=OPEN \
  bash "$SCRIPTS/orch.sh" --repo "$TMP" --mode ready-pickup --issue 2 --agent "$STUB_BIN/stub-agent" 2>&1)"
rc_pr_ok=$?
set -e
assert_eq "$rc_pr_ok" "0" "ready-pickup exits 0 when PR has green checks and mergeable"
assert_contains "$out_pr_ok" "done: issue 2 (PR 102 checks green, mergeable=MERGEABLE)" "done printed on green PR"

WT_PATH2="$(orch_worktree_path "$TMP" 2 issue-2)"
if [ -e "$WT_PATH2" ]; then
  FAILS=$((FAILS + 1))
  printf 'FAIL done issue worktree must be cleaned at run end: %s\n' "$WT_PATH2" >&2
else
  PASSES=$((PASSES + 1))
fi
assert_contains "$out_pr_ok" "removed $WT_PATH2" "orch-cleanup reported the done worktree"

echo "# orch ready-pickup (issue 12: no checks reported + ORCH_ALLOW_NO_CHECKS=1 -> done)"
set +e
out_nochk="$(ORCH_ALLOW_NO_CHECKS=1 _ORCH_CI_NO_CHECKS_GRACE=0 GH_STUB_NO_CHECKS=1 GH_STUB_PR_NUM=112 \
  bash "$SCRIPTS/orch.sh" --repo "$TMP" --mode ready-pickup --issue 12 --agent "$STUB_BIN/stub-agent" 2>&1)"
rc_nochk=$?
set -e
assert_eq "$rc_nochk" "0" "allow-no-checks reaches done when gh reports no checks"
assert_contains "$out_nochk" "done: issue 12 (PR 112 checks green" "done printed with no checks + opt-in"

echo "# orch ready-pickup (issue 3: checks green but mergeable=CONFLICTING -> blocked, exit nonzero)"
set +e
out_conf="$(GH_STUB_PR_NUM=103 GH_STUB_MERGEABLE=CONFLICTING GH_STUB_STATE=OPEN \
  bash "$SCRIPTS/orch.sh" --repo "$TMP" --mode ready-pickup --issue 3 --agent "$STUB_BIN/stub-agent" 2>&1)"
rc_conf=$?
set -e
assert_eq "$rc_conf" "1" "orch exits nonzero when PR mergeable fails"
assert_contains "$out_conf" "blocked: PR 103 is not mergeable (mergeable=CONFLICTING)" "blocked reason includes mergeable failure"
if echo "$out_conf" | grep -q "^done: issue 3"; then
  FAILS=$((FAILS + 1))
  printf 'FAIL done must not be reported when mergeable fails\n' >&2
else
  PASSES=$((PASSES + 1))
fi
orch_worktree_remove "$TMP" "$(orch_worktree_path "$TMP" 3 issue-3)" 2>/dev/null || true

echo "# orch ready-pickup (issue 4: checks green but state=CLOSED -> blocked, exit nonzero)"
set +e
out_closed="$(GH_STUB_PR_NUM=104 GH_STUB_MERGEABLE=MERGEABLE GH_STUB_STATE=CLOSED \
  bash "$SCRIPTS/orch.sh" --repo "$TMP" --mode ready-pickup --issue 4 --agent "$STUB_BIN/stub-agent" 2>&1)"
rc_closed=$?
set -e
assert_eq "$rc_closed" "1" "orch exits nonzero when PR state is CLOSED"
assert_contains "$out_closed" "blocked: PR 104 is not mergeable (mergeable=MERGEABLE)" "blocked when PR state is CLOSED"
if echo "$out_closed" | grep -q "^done: issue 4"; then
  FAILS=$((FAILS + 1))
  printf 'FAIL done must not be reported when PR is closed\n' >&2
else
  PASSES=$((PASSES + 1))
fi
orch_worktree_remove "$TMP" "$(orch_worktree_path "$TMP" 4 issue-4)" 2>/dev/null || true

echo "# orch ready-pickup multiple issues (issues 5, 6 with MAX_P=1 queues both sequentially)"
set +e
out_multi="$(GH_STUB_PR_NUM=105 GH_STUB_MERGEABLE=MERGEABLE GH_STUB_STATE=OPEN \
  bash "$SCRIPTS/orch.sh" --repo "$TMP" --mode ready-pickup --issue 5 --issue 6 --max-parallel 1 --agent "$STUB_BIN/stub-agent" 2>&1)"
rc_multi=$?
set -e
assert_eq "$rc_multi" "0" "orch exits 0 when all queued issues pass"
assert_contains "$out_multi" "worker id=5 branch=feat/5-issue-5" "issue 5 dispatched"
assert_contains "$out_multi" "worker id=6 branch=feat/6-issue-6" "issue 6 dispatched beyond MAX_P"
assert_contains "$out_multi" "done: issue 5" "done printed for issue 5"
assert_contains "$out_multi" "done: issue 6" "done printed for issue 6"
orch_worktree_remove "$TMP" "$(orch_worktree_path "$TMP" 5 issue-5)" 2>/dev/null || true
orch_worktree_remove "$TMP" "$(orch_worktree_path "$TMP" 6 issue-6)" 2>/dev/null || true

echo "# orch ready-pickup parallel pool (issues 9, 10 with MAX_P=2 overlap)"
# Slow stub so both workers are in-flight together under the cap
cat >"$STUB_BIN/slow-agent" <<'EOF'
#!/usr/bin/env bash
# Reviewer / verifier calls answer immediately; only the worker call leaves markers.
prompt="$(cat)"
mkdir -p .orch
case "$prompt" in
  *"Verifier (grounding node)"*) touch .orch/verifier-ok; exit 0 ;;
  *"Reviewer prompt"*) echo "REVIEW: approved"; exit 0 ;;
esac
marker_dir="${ORCH_PARALLEL_MARKERS:-/tmp/orch-parallel-markers}"
mkdir -p "$marker_dir"
# Prefer issue id from worker prompt path in cwd; fallback to pid
id="${ORCH_WORKER_ID:-${ORCH_WT##*/}}"
[ -n "$id" ] || id="$$"
date +%s%N >"$marker_dir/start.$id"
sleep 1
date +%s%N >"$marker_dir/end.$id"
exit 0
EOF
chmod +x "$STUB_BIN/slow-agent"
MARKERS="$(mktemp -d)"
set +e
out_par="$(ORCH_PARALLEL_MARKERS="$MARKERS" GH_STUB_PR_NUM=109 GH_STUB_MERGEABLE=MERGEABLE GH_STUB_STATE=OPEN \
  bash "$SCRIPTS/orch.sh" --repo "$TMP" --mode ready-pickup --issue 9 --issue 10 --max-parallel 2 --agent "$STUB_BIN/slow-agent" 2>&1)"
rc_par=$?
set -e
assert_eq "$rc_par" "0" "parallel pool exits 0 when both workers done"
assert_contains "$out_par" "ORCH_MAX_PARALLEL=2" "logs parallel dispatch"
assert_contains "$out_par" "done: issue 9" "done printed for issue 9"
assert_contains "$out_par" "done: issue 10" "done printed for issue 10"
shopt -s nullglob
# Ignore stray markers from non-worker agent invocations (e.g. wrong ORCH_WT).
starts=("$MARKERS"/start.[0-9]*)
ends=("$MARKERS"/end.[0-9]*)
shopt -u nullglob
if [ "${#starts[@]}" -ge 2 ] && [ "${#ends[@]}" -ge 2 ]; then
  # Overlap: earliest end must be after latest start
  latest_start=0
  earliest_end=
  for f in "${starts[@]}"; do
    t=$(cat "$f")
    [ "$t" -gt "$latest_start" ] && latest_start=$t
  done
  for f in "${ends[@]}"; do
    t=$(cat "$f")
    if [ -z "$earliest_end" ] || [ "$t" -lt "$earliest_end" ]; then
      earliest_end=$t
    fi
  done
  if [ -n "$earliest_end" ] && [ "$earliest_end" -gt "$latest_start" ]; then
    PASSES=$((PASSES + 1))
  else
    FAILS=$((FAILS + 1))
    printf 'FAIL expected overlapping parallel workers (latest_start=%s earliest_end=%s starts=%s ends=%s)\n' \
      "$latest_start" "${earliest_end:-none}" "${#starts[@]}" "${#ends[@]}" >&2
    ls -la "$MARKERS" >&2 || true
  fi
else
  FAILS=$((FAILS + 1))
  printf 'FAIL expected 2 start/end marker pairs (got starts=%s ends=%s)\nout:\n%s\n' \
    "${#starts[@]}" "${#ends[@]}" "$out_par" >&2
  ls -la "$MARKERS" >&2 || true
fi
rm -rf "$MARKERS"
orch_worktree_remove "$TMP" "$(orch_worktree_path "$TMP" 9 issue-9)" 2>/dev/null || true
orch_worktree_remove "$TMP" "$(orch_worktree_path "$TMP" 10 issue-10)" 2>/dev/null || true

echo "# orch ready-pickup (issue 7 blocked, issue 8 done -> overall exit nonzero)"
set +e
out_partial="$(GH_STUB_MERGEABLE=MERGEABLE GH_STUB_STATE=OPEN \
  bash "$SCRIPTS/orch.sh" --repo "$TMP" --mode ready-pickup --issue 7 --issue 8 --agent "$STUB_BIN/stub-agent" 2>&1)"
rc_partial=$?
set -e
assert_eq "$rc_partial" "1" "overall exit is nonzero when any worker is blocked"
assert_contains "$out_partial" "blocked: issue 7 (no PR for branch feat/7-issue-7)" "issue 7 is blocked"
assert_contains "$out_partial" "done: issue 8 (PR 108 checks green, mergeable=MERGEABLE)" "issue 8 is done"
assert_file "$(orch_worktree_path "$TMP" 7 issue-7)" "blocked issue keeps its worktree"
if [ -e "$(orch_worktree_path "$TMP" 8 issue-8)" ]; then
  FAILS=$((FAILS + 1))
  printf 'FAIL done issue 8 worktree must be cleaned\n' >&2
else
  PASSES=$((PASSES + 1))
fi
orch_worktree_remove "$TMP" "$(orch_worktree_path "$TMP" 7 issue-7)" 2>/dev/null || true
orch_worktree_remove "$TMP" "$(orch_worktree_path "$TMP" 8 issue-8)" 2>/dev/null || true

echo "# orch ready-pickup (issue 11: reviewer says changes_requested twice -> blocked, exit nonzero)"
set +e
out_review="$(STUB_REVIEW=changes_requested GH_STUB_PR_NUM=111 GH_STUB_MERGEABLE=MERGEABLE GH_STUB_STATE=OPEN \
  bash "$SCRIPTS/orch.sh" --repo "$TMP" --mode ready-pickup --issue 11 --agent "$STUB_BIN/stub-agent" 2>&1)"
rc_review=$?
set -e
assert_eq "$rc_review" "1" "orch exits nonzero when review stays changes_requested"
assert_contains "$out_review" "review: reviewer round 2" "one fix iteration then a second review"
assert_contains "$out_review" "blocked: issue 11 review: changes_requested" "blocked with review reason"
if echo "$out_review" | grep -q "^done: issue 11"; then
  FAILS=$((FAILS + 1))
  printf 'FAIL done must not be reported when review is rejected twice\n' >&2
else
  PASSES=$((PASSES + 1))
fi
orch_worktree_remove "$TMP" "$(orch_worktree_path "$TMP" 11 issue-11)" 2>/dev/null || true

echo "# Ctrl-C leaves no agent child (issue 30: slow stub agent receives INT on orch)"
MARK="orch-h5-sleeper-$$"
cat >"$STUB_BIN/$MARK" <<'EOS'
#!/usr/bin/env bash
cat >/dev/null
while :; do sleep 1; done
EOS
chmod +x "$STUB_BIN/$MARK"
# orch runs in its own session/process group (setsid), so `kill 0` in its trap can only
# reach the stub. SIGINT is reset to default because async jobs (and nohup) start with it ignored,
# and a signal ignored on entry cannot be trapped.
PIDF="$TMP/orch30.pid"
set -m
setsid bash -c 'echo $$ >"$1"; shift; exec "$@"' _ "$PIDF" \
  env --default-signal=INT ORCH_VERIFY=true GH_STUB_NO_PR=1 bash "$SCRIPTS/orch.sh" --repo "$TMP" --mode ready-pickup --issue 30 \
  --agent "$STUB_BIN/$MARK" >/dev/null 2>&1 &
set +m
for _ in $(seq 100); do [ -s "$PIDF" ] && pgrep -f "$MARK" >/dev/null && break; sleep 0.1; done
orch_pid="$(cat "$PIDF" 2>/dev/null || true)"
if [ -n "$orch_pid" ] && [ "$(ps -o pgid= -p "$orch_pid" | tr -d ' ')" = "$orch_pid" ] && pgrep -f "$MARK" >/dev/null; then
  PASSES=$((PASSES + 1))
  kill -INT "$orch_pid"
  for _ in $(seq 50); do kill -0 "$orch_pid" 2>/dev/null || break; sleep 0.1; done
  sleep 0.3
  if pgrep -f "$MARK" >/dev/null; then
    FAILS=$((FAILS + 1))
    printf 'FAIL agent child survived INT\n' >&2
    kill -KILL -- "-$orch_pid" 2>/dev/null || true
  else
    PASSES=$((PASSES + 1))
  fi
else
  # Never signal anything unless orch is the leader of its own group.
  FAILS=$((FAILS + 1))
  printf 'FAIL orch did not start as its own process group leader with a running stub agent\n' >&2
fi
orch_worktree_remove "$TMP" "$(orch_worktree_path "$TMP" 30 issue-30)" 2>/dev/null || true

echo "# orch from inside a linked worktree keeps .orch/ at the main toplevel"
LINKED="$TMP.linked"
git -C "$TMP" worktree add -q -b linked-test "$LINKED"
out_nested="$(cd "$LINKED" && bash "$SCRIPTS/orch.sh" --mode ready-pickup --issue 31 --dry-run)"
assert_contains "$out_nested" "wt=$TMP/.orch/worktrees/31-issue-31" "worktree path derives from main toplevel"
if [ -e "$LINKED/.orch" ]; then
  FAILS=$((FAILS + 1))
  printf 'FAIL .orch created inside linked worktree: %s\n' "$LINKED/.orch" >&2
else
  PASSES=$((PASSES + 1))
fi
assert_eq "$(orch_repo_root "$LINKED")" "$TMP" "orch_repo_root resolves a linked worktree to the main checkout"
assert_eq "$(orch_repo_root "$TMP")" "$TMP" "orch_repo_root keeps the main checkout"
git -C "$TMP" worktree remove --force "$LINKED"

summary
